/// [`PTY`] Controller: Emulate host terminal emulator, verifying raw outbound [`OSC`]
/// sequences.
///
/// Connected to the controller side of the [`PTY`]. Reads output emitted by the child
/// process and validates exact byte-level wire formatting for each [`OscSender`]
/// operation.
///
/// [`OSC`]: crate::osc_codes::OscSequence
/// [`OscSender`]: crate::core::ansi::osc::OscSender
/// [`PTY`]: https://en.wikipedia.org/wiki/Pseudoterminal
fn controller(context: PtyTestContext) {
    let PtyTestContext {
        pty_pair,
        child,
        mut buf_reader,
        writer,
    } = context;

    eprintln!("{GLYPH_CONTROLLER} PTY Controller: Starting OSC sender test...");
    eprintln!(
        "{GLYPH_WAITING} PTY Controller: Waiting for controlled process to start..."
    );

    // Wait for controlled to confirm it's running and ready.
    child
        .wait_for_ready(&mut buf_reader, MSG_CONTROLLED_READY)
        .expect("Failed to wait for ready signal");

    for test_case in generate_test_cases() {
        let desc = test_case.description;
        let prefix = &test_case.prefix;
        let expected_sequence = &test_case.expected_sequence;

        eprintln!("{GLYPH_WAITING} Controller: Verifying {desc}...");
        let line = child.read_line_state(&mut buf_reader, |l| l.contains(prefix));
        assert!(
            line.contains(expected_sequence),
            "Expected sequence {expected_sequence:?} for {desc}, got: {line:?}"
        );
        eprintln!("  {GLYPH_SUCCESS} {desc} verified: {line:?}");
    }

    eprintln!("{GLYPH_CONTROLLER_CLEANUP} PTY Controller: Cleaning up...");
    drop(writer);
    child.drain_and_wait(buf_reader, pty_pair);

    eprintln!("{GLYPH_SUCCESS} PTY Controller: Test passed!");
}

/// [`PTY`] Controlled: Emits outbound [`OSC`] sequences via [`OscSender`].
///
/// Runs inside the child process connected to the controlled side of the [`PTY`].
/// Exercises each [`OscSender`] method on standard output.
///
/// [`OSC`]: crate::osc_codes::OscSequence
/// [`OscSender`]: crate::core::ansi::osc::OscSender
/// [`PTY`]: https://en.wikipedia.org/wiki/Pseudoterminal
fn controlled() {
    println!("{MSG_TEST_RUNNING}");
    println!("{MSG_CONTROLLED_STARTING}");
    std::io::stdout().flush().expect("Failed to flush stdout");

    eprintln!("{GLYPH_CONTROLLED} PTY Controlled: Starting...");
    let output_device = OutputDevice::new_stdout();
    let mut osc_sender = OscSender::new(&output_device);

    // Signal ready to controller.
    println!("{MSG_CONTROLLED_READY}");
    std::io::stdout().flush().expect("Failed to flush stdout");

    // 1. Title and Icon.
    osc_sender
        .send_set_title_and_tab(constants::TITLE_AND_ICON_TEXT)
        .expect("Failed to send title and icon");
    println!();
    std::io::stdout().flush().expect("Failed to flush stdout");

    // 2. Title only.
    osc_sender
        .send_set_title(constants::TITLE_ONLY_TEXT)
        .expect("Failed to send title only");
    println!();
    std::io::stdout().flush().expect("Failed to flush stdout");

    // 3. Hyperlink with correlation ID.
    osc_sender
        .send_set_hyperlink(constants::HYPERLINK_URI, Some(constants::HYPERLINK_ID))
        .expect("Failed to send hyperlink start");
    println!();
    std::io::stdout().flush().expect("Failed to flush stdout");

    // 4. Hyperlink close.
    osc_sender
        .send_clear_hyperlink()
        .expect("Failed to send clear hyperlink");
    println!();
    std::io::stdout().flush().expect("Failed to flush stdout");

    // 5. Progress update.
    osc_sender
        .send_set_progress(pc!(constants::PROGRESS_PERCENT).unwrap())
        .expect("Failed to send progress update");
    println!();
    std::io::stdout().flush().expect("Failed to flush stdout");

    // 6. Progress clear.
    osc_sender
        .send_clear_progress()
        .expect("Failed to send clear progress");
    println!();
    std::io::stdout().flush().expect("Failed to flush stdout");

    // 7. System clipboard copy.
    osc_sender
        .send_set_clipboard(ClipboardTarget::System, constants::CLIPBOARD_SYSTEM_DATA)
        .expect("Failed to send system clipboard");
    println!();
    std::io::stdout().flush().expect("Failed to flush stdout");

    // 8. Primary clipboard copy.
    osc_sender
        .send_set_clipboard(ClipboardTarget::Primary, constants::CLIPBOARD_PRIMARY_DATA)
        .expect("Failed to send primary clipboard");
    println!();
    std::io::stdout().flush().expect("Failed to flush stdout");

    eprintln!("{GLYPH_CONTROLLED} PTY Controlled: Completed successfully");
}

// -------------------------------------------------------------------------------------------------
// Test cases
// -------------------------------------------------------------------------------------------------

#[derive(Debug, Clone)]
struct TestCase {
    pub description: &'static str,
    pub prefix: String,
    pub expected_sequence: String,
}

impl TestCase {
    pub fn new(
        description: &'static str,
        prefix: String,
        expected_sequence: String,
    ) -> Self {
        Self {
            description,
            prefix,
            expected_sequence,
        }
    }
}

fn generate_test_cases() -> Vec<TestCase> {
    let clip_system_b64 = BASE64_STANDARD.encode(constants::CLIPBOARD_SYSTEM_DATA);
    let clip_primary_b64 = BASE64_STANDARD.encode(constants::CLIPBOARD_PRIMARY_DATA);

    vec![
        // 1. OSC 0: Set Title and Icon (ESC ] 0 ; <title> BEL).
        TestCase::new(
            "OSC 0 (Title & Icon)",
            expected::title_and_icon_prefix(),
            expected::title_and_icon(constants::TITLE_AND_ICON_TEXT),
        ),
        // 2. OSC 2: Set Title Only (ESC ] 2 ; <title> BEL).
        TestCase::new(
            "OSC 2 (Title Only)",
            expected::title_prefix(),
            expected::title(constants::TITLE_ONLY_TEXT),
        ),
        // 3. OSC 8: Hyperlink Start with ID (ESC ] 8 ; <id> ; <uri> BEL).
        TestCase::new(
            "OSC 8 (Hyperlink Start)",
            expected::hyperlink_prefix(),
            expected::hyperlink_start(constants::HYPERLINK_ID, constants::HYPERLINK_URI),
        ),
        // 4. OSC 8: Hyperlink End (ESC ] 8 ; ; BEL).
        TestCase::new(
            "OSC 8 (Hyperlink End)",
            expected::hyperlink_clear_prefix(),
            expected::hyperlink_clear(),
        ),
        // 5. OSC 9;4;1: Progress Update (ESC ] 9 ; 4 ; 1 ; <percent> ESC \\).
        TestCase::new(
            "OSC 9;4;1 (Progress Update)",
            expected::progress_update_prefix(),
            expected::progress_update(constants::PROGRESS_PERCENT),
        ),
        // 6. OSC 9;4;0;0: Progress Cleared (ESC ] 9 ; 4 ; 0 ; 0 ESC \\).
        TestCase::new(
            "OSC 9;4;0;0 (Progress Cleared)",
            expected::progress_clear_prefix(),
            expected::progress_clear(),
        ),
        // 7. OSC 52: System Clipboard (ESC ] 52 ; c ; <base64> BEL).
        TestCase::new(
            "OSC 52 (System Clipboard)",
            expected::clipboard_prefix('c'),
            expected::clipboard('c', &clip_system_b64),
        ),
        // 8. OSC 52: Primary Clipboard (ESC ] 52 ; p ; <base64> BEL).
        TestCase::new(
            "OSC 52 (Primary Clipboard)",
            expected::clipboard_prefix('p'),
            expected::clipboard('p', &clip_primary_b64),
        ),
    ]
}

