// XMARK: pty test faking terminal emulator (in controller)

//! [`PTY`]-based integration test for outbound [`OSC`] sequence emission via
//! [`OscSender`].
//!
//! Validates that [`OscSender`] correctly formats and transmits one-way outbound [`OSC`]
//! commands over standard output to the controller [`PTY`] peer:
//! - Window Title & Icon ([`OSC 0`])
//! - Window Title Only ([`OSC 2`])
//! - Clickable Hyperlink Start with ID and URI ([`OSC 8`])
//! - Hyperlink Close ([`OSC 8;;`])
//! - Taskbar & Tab Progress Update ([`OSC 9;4;1;percent`])
//! - Progress Cleared ([`OSC 9;4;0;0`])
//! - System Clipboard Copy ([`OSC 52;c;<base64>`])
//! - Primary Selection Clipboard Copy ([`OSC 52;p;<base64>`])
//!
//! # Architecture and Process Roles
//!
//! In this test, the controller process simulates a host terminal emulator while the
//! controlled child runs our TUI input engine. For the overall architecture and testing
//! philosophy, see the [process roles documentation].
//!
//! 1. **[`PTY`] Controller (Simulated Terminal Emulator / Wire Validator)**:
//!    - Connected to the controller side of the [`PTY`].
//!    - Simulates an external host terminal emulator validating wire protocol syntax.
//!    - Reads raw byte sequences emitted by the controlled child over [`stdout`].
//!    - Asserts that every outbound command matches exact byte-level wire formatting,
//!      command numbers, delimiters, base64 payloads, and string terminators (`BEL` or
//!      `ST`).
//!
//! 2. **[`PTY`] Controlled (System Under Test / TUI Input Engine)**:
//!    - Represents the real TUI application running inside the child subprocess connected
//!      to the controlled side of the [`PTY`].
//!    - Initializes [`OscSender`] on [`OutputDevice::new_stdout()`].
//!    - Sequentially executes outbound command methods covering window titles,
//!      hyperlinks, taskbar progress updates, and clipboard copies.
//!
//! # Unidirectional (Fire-and-Forget) Protocol Architecture
//!
//! Unlike bidirectional query protocols (such as terminal color queries tested in
//! [`pty_osc_color_test`]), all outbound commands (generated by the controlled child)
//! exercised here are strictly **fire-and-forget**. So the controller is not required to
//! provide any response to the command (not query). A real terminal emulator is expected
//! to do the following with ECMA-48, [`XTerm`] control sequences:
//! - It acts upon outbound [`OSC`] sequences internally (updating window titles,
//!   registering hyperlink click regions, rendering taskbar progress, or populating the
//!   host desktop clipboard).
//! - It **never** writes response bytes back to the controlled [`PTY`] for these
//!   commands.
//!
//! > So, a full mock terminal emulator is neither needed nor appropriate for this test.
//! > The controller process acts as a passive wire validator on the controller [`PTY`],
//! > asserting that [`OscSender`] correctly formatted and emitted each sequence without
//! > needing to synthesize any mock terminal response.
//!
//! # Run with:
//!
//! ```bash
//! cargo test -p r3bl_tui --lib test_pty_osc_sender -- --nocapture
//! ```
//!
//! [`OSC 0`]: crate::core::ansi::osc::OscSequence::SetTitleAndIcon
//! [`OSC 2`]: crate::core::ansi::osc::OscSequence::SetTitle
//! [`OSC 52;c;<base64>`]: crate::core::ansi::osc::OscSequence::ClipboardSet
//! [`OSC 52;p;<base64>`]: crate::core::ansi::osc::OscSequence::ClipboardSet
//! [`OSC 8;;`]: crate::core::ansi::osc::OscSequence::HyperlinkEnd
//! [`OSC 8`]: crate::core::ansi::osc::OscSequence::HyperlinkStart
//! [`OSC 9;4;0;0`]: crate::core::ansi::osc::OscSequence::ProgressCleared
//! [`OSC 9;4;1;percent`]: crate::core::ansi::osc::OscSequence::ProgressUpdate
//! [`OSC`]: crate::core::ansi::osc::OscSequence
//! [`OscSender`]: crate::core::ansi::osc::OscSender
//! [`OutputDevice::new_stdout()`]: crate::OutputDevice::new_stdout
//! [`pty_osc_color_test`]: mod@super::pty_osc_color_test
//! [`PTY`]: https://en.wikipedia.org/wiki/Pseudoterminal
//! [`stdout`]: std::io::stdout
//! [`XTerm`]: https://en.wikipedia.org/wiki/Xterm
//! [process roles documentation]: mod@super#architecture-and-process-roles

